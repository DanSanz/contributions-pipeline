"""Generate the feed record types in src/generated/ from contracts/feed_contract.json.

    python tools/generate_feed_types.py           write src/generated/
    python tools/generate_feed_types.py --check   exit 1 if src/generated/ is out of date

The feed contract is owned by the feed-contract group (see CODEOWNERS). To change a
record, change the contract and regenerate; edits made by hand are overwritten.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTRACT_PATH = ROOT / "contracts" / "feed_contract.json"
OUTPUT_DIR = ROOT / "src" / "generated"

BANNER = (
    "# Code generated by tools/generate_feed_types.py from contracts/feed_contract.json. DO NOT EDIT.\n"
)


def load_contract(path: Path = CONTRACT_PATH) -> dict:
    return json.loads(Path(path).read_text(encoding="utf-8"))


def _names(fields: list[dict], predicate) -> str:
    chosen = sorted(field["name"] for field in fields if predicate(field))
    if not chosen:
        return "frozenset()"
    return "frozenset({" + ", ".join(f'"{name}"' for name in chosen) + "})"


def _comment(field: dict) -> str:
    parts = [field[key] for key in ("format", "note") if key in field]
    if field["class"] != "internal":
        parts.append(field["class"])
    return f"  # {'; '.join(parts)}" if parts else ""


def render_record_module(feed: dict, version: str) -> str:
    fields = feed["fields"]
    lines = [
        BANNER.rstrip("\n"),
        f'"""{feed["feed_type"]} feed, contract {version}. {feed["description"]}"""',
        "",
        "from dataclasses import dataclass",
        "from typing import ClassVar",
        "",
        "",
        "@dataclass(frozen=True, slots=True)",
        f"class {feed['record']}:",
        f'    """One detail record of a {feed["feed_type"]} file. Values are text, trimmed, as received."""',
        "",
    ]
    lines += [f"    {field['name']}: str{_comment(field)}" for field in fields]
    columns = ", ".join(f'"{field["name"]}"' for field in fields)
    lines += [
        "",
        f"    COLUMNS: ClassVar[tuple[str, ...]] = ({columns})",
        f"    REQUIRED: ClassVar[frozenset[str]] = {_names(fields, lambda f: f['required'])}",
        f"    PERSONAL: ClassVar[frozenset[str]] = {_names(fields, lambda f: f['class'] == 'personal')}",
        f"    CONFIDENTIAL: ClassVar[frozenset[str]] = "
        f"{_names(fields, lambda f: f['class'] == 'confidential')}",
        "",
    ]
    return "\n".join(lines)


def render_package_init(contract: dict) -> str:
    feeds = sorted(contract["feeds"], key=lambda feed: feed["module"])
    lines = [
        BANNER.rstrip("\n"),
        '"""Record types for the inbound employer feeds, generated from the feed contract."""',
        "",
    ]
    lines += [f"from generated.{feed['module']} import {feed['record']}" for feed in feeds]
    lines += [
        "",
        f'CONTRACT_VERSION = "{contract["version"]}"',
        "",
        "FEED_TYPES = {",
    ]
    lines += [f'    "{feed["feed_type"]}": {feed["record"]},' for feed in contract["feeds"]]
    lines += [
        "}",
        "",
        "__all__ = [" + ", ".join(f'"{name}"' for name in
                                 ["CONTRACT_VERSION", "FEED_TYPES"] + [f["record"] for f in feeds]) + "]",
        "",
    ]
    return "\n".join(lines)


def render_all(contract: dict) -> dict[str, str]:
    """File name -> source text for every file in src/generated/."""
    files = {"__init__.py": render_package_init(contract)}
    for feed in contract["feeds"]:
        files[f"{feed['module']}.py"] = render_record_module(feed, contract["version"])
    return files


def out_of_date(contract: dict, output_dir: Path = OUTPUT_DIR) -> list[str]:
    """Names of generated files that are missing or differ from what the contract produces."""
    stale = []
    for name, text in render_all(contract).items():
        path = output_dir / name
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            stale.append(name)
    return stale


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="report stale files and exit 1")
    args = parser.parse_args(argv)
    contract = load_contract()
    if args.check:
        stale = out_of_date(contract)
        for name in stale:
            print(f"out of date: src/generated/{name}")
        return 1 if stale else 0
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    for name, text in render_all(contract).items():
        (OUTPUT_DIR / name).write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote src/generated/{name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
